const GLYPH_H = 7;
/** Las mayúsculas con tilde miden 9 filas: la tilde sobresale por arriba. */
const TALL_H = 9;
const SPACE_W = 3;

export const FONT = 'px';
export const FONT_PLAIN = 'pxplain';

type CharData = {
  x: number;
  y: number;
  width: number;
  height: number;
  centerX: number;
  centerY: number;
  xOffset: number;
  yOffset: number;
  xAdvance: number;
  data: object;
  kerning: object;
  u0: number;
  v0: number;
  u1: number;
  v1: number;
};

function buildFont(scene: Phaser.Scene, key: string, outlined: boolean): void {
  const pad = outlined ? 1 : 0;
  const cellH = TALL_H + pad * 2;
  const entries = Object.entries(G);
  const widths = entries.map(([, rows]) => rows[0].length + pad * 2);
  const texW = widths.reduce((a, b) => a + b, 0) + 8;
  if (scene.textures.exists(key)) scene.textures.remove(key);
  const tex = scene.textures.createCanvas(key, texW, cellH)!;
  const ctx = tex.getContext();

  const chars: Record<number, CharData> = {};
  let x = 0;
  entries.forEach(([ch, rows], idx) => {
    const gw = rows[0].length;
    const gh = rows.length;
    const top = TALL_H - gh;
    const cw = widths[idx];
    // Píxeles del glifo
    const on = (gx: number, gy: number) => gx >= 0 && gy >= 0 && gx < gw && gy < gh && rows[gy][gx] === '#';
    if (outlined) {
      ctx.fillStyle = PAL.outline;
      for (let gy = -1; gy <= gh; gy++) {
        for (let gx = -1; gx <= gw; gx++) {
          if (on(gx, gy)) continue;
          if (on(gx - 1, gy) || on(gx + 1, gy) || on(gx, gy - 1) || on(gx, gy + 1) || on(gx - 1, gy - 1) || on(gx + 1, gy + 1) || on(gx + 1, gy - 1) || on(gx - 1, gy + 1)) {
            ctx.fillRect(x + gx + pad, top + gy + pad, 1, 1);
          }
        }
      }
    }
    ctx.fillStyle = '#ffffff';
    for (let gy = 0; gy < gh; gy++) for (let gx = 0; gx < gw; gx++) if (on(gx, gy)) ctx.fillRect(x + gx + pad, top + gy + pad, 1, 1);

    const advance = outlined ? gw + 1 : gw + 1;
    const h = gh + pad * 2;
    chars[ch.charCodeAt(0)] = {
      x,
      y: top,
      width: cw,
      height: h,
      centerX: Math.floor(cw / 2),
      centerY: Math.floor(h / 2),
      xOffset: 0,
      yOffset: GLYPH_H - gh,
      xAdvance: advance,
      data: {},
      kerning: {},
      u0: x / texW,
      v0: top / cellH,
      u1: (x + cw) / texW,
      v1: (top + h) / cellH,
    };
    x += cw;
  });
  // Espacio: un glifo vacío
  chars[32] = {
    x: texW - 4,
    y: 0,
    width: 1,
    height: cellH,
    centerX: 0,
    centerY: 0,
    xOffset: 0,
    yOffset: 0,
    xAdvance: SPACE_W,
    data: {},
    kerning: {},
    u0: (texW - 4) / texW,
    v0: 0,
    u1: (texW - 3) / texW,
    v1: 1,
  };
  tex.refresh();

  scene.cache.bitmapFont.add(key, {
    data: {
      font: key,
      size: GLYPH_H + pad * 2,
      lineHeight: GLYPH_H + 3,
      retroFont: true,
      chars,
    },
    texture: key,
    frame: null,
  });
}

export function buildFonts(scene: Phaser.Scene): void {
  buildFont(scene, FONT, true);
  buildFont(scene, FONT_PLAIN, false);
}

/** Normaliza el texto para la fuente: mayúsculas y sustitución de caracteres sin glifo. */
export function fontText(s: string): string {
  return s
    .toUpperCase()
    .split('')
    .map((c) => (c === ' ' || c === '\n' || G[c] ? c : c === 'À' ? 'A' : c === 'È' ? 'E' : c === 'Ò' ? 'O' : c === 'Ç' ? 'C' : '?'))
    .join('');
}
